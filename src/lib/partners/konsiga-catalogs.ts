export function getKonsigaStatusMeta(status: string | null | undefined): KonsigaStatusMeta {
  if (!status) {
    return {
      label: 'Aguardando retorno',
      description: 'Sincronize para consultar o status mais recente na Konsiga.',
      tone: 'info',
    };
  }
  const key = stripAccents(status);
  return (
    STATUS_MAP[key] || {
      label: status,
      description: 'Status retornado pela Konsiga.',
      tone: 'info',
    }
  );
}
